-- 테트로미노 7종의 모양(SRS 기준), 색상, 회전 상태, 월킥 테이블
local Tetromino = {}

local base = {
    I = { size = 4, color = { 0.20, 0.78, 0.92 }, cells = { { 0, 1 }, { 1, 1 }, { 2, 1 }, { 3, 1 } } },
    J = { size = 3, color = { 0.30, 0.42, 0.90 }, cells = { { 0, 0 }, { 0, 1 }, { 1, 1 }, { 2, 1 } } },
    L = { size = 3, color = { 0.95, 0.55, 0.15 }, cells = { { 2, 0 }, { 0, 1 }, { 1, 1 }, { 2, 1 } } },
    O = { size = 2, color = { 0.95, 0.80, 0.15 }, cells = { { 0, 0 }, { 1, 0 }, { 0, 1 }, { 1, 1 } } },
    S = { size = 3, color = { 0.35, 0.80, 0.30 }, cells = { { 1, 0 }, { 2, 0 }, { 0, 1 }, { 1, 1 } } },
    T = { size = 3, color = { 0.65, 0.30, 0.85 }, cells = { { 1, 0 }, { 0, 1 }, { 1, 1 }, { 2, 1 } } },
    Z = { size = 3, color = { 0.90, 0.25, 0.25 }, cells = { { 0, 0 }, { 1, 0 }, { 1, 1 }, { 2, 1 } } },
}

local function rotateCW(cells, size)
    local out = {}
    for i, c in ipairs(cells) do
        out[i] = { size - 1 - c[2], c[1] }
    end
    return out
end

Tetromino.types = { "I", "J", "L", "O", "S", "T", "Z" }

Tetromino.data = {}
for name, def in pairs(base) do
    local rotations = { def.cells }
    for r = 2, 4 do
        rotations[r] = rotateCW(rotations[r - 1], def.size)
    end
    Tetromino.data[name] = { size = def.size, color = def.color, rotations = rotations }
end

